//! Fixed codec constants of the BCPack block stage: index codebooks and the built-in endpoint histories.
//!
//! Provenance: these tables were recovered clean-room by the upstream Leonida project (`tools/bcpack_tables.py`,
//! from public BCn formats, the BCPack patent, and fitting against retail chunks); they are codec constants, not
//! game assets. Every history entry carries the status upstream gave it:
//!
//! - `Confirmed`: verified against reference data.
//! - `Provisional`: fitted and uncertain, so a decode that depends on it is refused unless the caller opts in
//!   with `DecodeOptions::allow_provisional`.
//! - `Unknown`: not recovered.
//!
//! Index codebooks map a lane symbol (a rank) to the pixel indices it stands for.

/// One built-in history entry of `N` endpoint fields.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Hist<const N: usize> {
    Unknown,
    Provisional([u8; N]),
    Confirmed([u8; N]),
}

